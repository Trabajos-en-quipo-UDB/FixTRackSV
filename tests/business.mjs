import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
process.env.FIXTRACK_DB=path.join(mkdtempSync(path.join(tmpdir(),'fixtrack-test-')),'test.sqlite');
const {db,insert,one,all}=await import('../src/lib/db.js');
const {mutate,snapshot}=await import('../src/lib/service.js');
const {hashPassword,verifyPassword}=await import('../src/lib/passwords.js');
const hash=hashPassword('Testing-password');
assert.equal(verifyPassword('Testing-password',hash),true);assert.equal(verifyPassword('incorrect',hash),false);assert.notEqual(hashPassword('Testing-password'),hash);
function user(name,role) { const id=insert('users',{name,email:`${name}@test.example`,role,active:1,password:hash});return one('users',id); }
const admin=user('Admin','Administrador'),tech=user('Tech','Técnico'),other=user('Other','Técnico'),reception=user('Reception','Recepcionista');
const act=(u,r,b,id=null,method=id?'PATCH':'POST')=>mutate(u,r,method,id,b);
function denied(fn,status){assert.throws(fn,e=>e.status===status);}
denied(()=>act(tech,'clients',{name:'Cliente',phone:'77777777'}),403);
denied(()=>act(reception,'parts',{name:'SSD',price:20}),403);
const client=act(reception,'clients',{name:'Cliente de prueba',phone:'77777777'});
const equipment=act(reception,'equipment',{client_id:client.id,type:'Laptop',brand:'Dell',model:'Latitude'});
const order=act(reception,'orders',{equipment_id:equipment.id,technician_id:tech.id,problem:'El equipo no enciende',priority:'Alta'});
assert.equal(snapshot(other).orders.length,0);assert.equal(snapshot(tech).orders.length,1);
denied(()=>act(other,'orders',{status:'En diagnóstico'},order.id),403);
denied(()=>act(tech,'orders',{status:'Entregado'},order.id),403);
denied(()=>act(tech,'orders',{status:'Reparado'},order.id),422);
act(tech,'orders',{status:'En diagnóstico',service_cost:25},order.id);
denied(()=>act(reception,'diagnostics',{order_id:order.id,finding:'Una falla cualquiera'}),403);
act(tech,'diagnostics',{order_id:order.id,finding:'SSD defectuoso',work:'Sustitución'});
const part=act(admin,'parts',{name:'SSD 500GB',price:40});
denied(()=>act(tech,'lines',{order_id:order.id,part_id:part.id,quantity:1.5}),422);
act(tech,'lines',{order_id:order.id,part_id:part.id,quantity:1});
denied(()=>act(reception,'payments',{order_id:order.id,amount:66,method:'Efectivo'}),422);
for (const status of ['Esperando aprobación','En reparación','Reparado','Listo para entregar']) act(tech,'orders',{status},order.id);
const before=all('history').length;
denied(()=>act(reception,'orders',{status:'Entregado',technician_id:tech.id},order.id),422);
assert.equal(all('history').length,before,'Rollback debe conservar el historial');
act(reception,'payments',{order_id:order.id,amount:65,method:'Efectivo'});
denied(()=>act(admin,'orders',{status:'Cancelado',note:'Prueba de cancelación'},order.id),422);
denied(()=>act(tech,'orders',{service_cost:0},order.id),422);
act(reception,'orders',{status:'Entregado',technician_id:tech.id},order.id);
denied(()=>act(tech,'diagnostics',{order_id:order.id,finding:'Edición posterior al cierre'}),422);
assert.throws(()=>act(admin,'clients',{},client.id,'DELETE'),/FOREIGN KEY/);
denied(()=>act(admin,'orders',{},order.id,'DELETE'),422);
assert.equal(all('history').filter(h=>h.order_id===order.id).length,7);
assert.equal(one('orders',order.id).status,'Entregado');
db().prepare('INSERT INTO sessions VALUES (?,?,?)').run('test-token',tech.id,Date.now()+10000);
act(admin,'users',{role:'Técnico',active:false},tech.id);
assert.equal(db().prepare('SELECT count(*) AS n FROM sessions').get().n,0);
db().close();globalThis.fixtrackDb=null;
assert.equal(one('orders',order.id).status,'Entregado','Persistencia después de reabrir');
db().close();globalThis.fixtrackDb=null;
console.log('OK: 22 verificaciones de contraseñas, permisos, aislamiento, cálculos, transiciones, rollback, integridad, historial, revocación y persistencia.');
